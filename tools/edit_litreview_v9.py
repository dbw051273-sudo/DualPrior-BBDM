def get_rid(url):
    for rid, rel in part.rels.items():
        if rel.is_external and rel.target_ref == url:
            return rid
    return part.relate_to(url, RT.HYPERLINK, is_external=True)


def esc(t):
    return t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def rebuild(p, text):
    """清空段落内容（保留 pPr），按新文本重建，[N] 重建为超链接。"""
    pPr = p._p.find(qn("w:pPr"))
    for child in list(p._p):
        if child is not pPr:
            p._p.remove(child)
    for seg in re.split(r"(\[\d+\])", text):
        if not seg:
            continue
        m = re.fullmatch(r"\[(\d+)\]", seg)
        if m and int(m.group(1)) in REF_URL:
            rid = get_rid(REF_URL[int(m.group(1))])
            p._p.append(parse_xml(
                f'<w:hyperlink {nsdecls("w", "r")} r:id="{rid}">'
                f'<w:r>{LINK_RPR}<w:t xml:space="preserve">{esc(seg)}</w:t></w:r>'
                f"</w:hyperlink>"))
        else:
            r = OxmlElement("w:r")
            if base_rPr is not None:
                r.append(copy.deepcopy(base_rPr))
            t = OxmlElement("w:t")
            t.set(qn("xml:space"), "preserve")
            t.text = seg
            r.append(t)
            p._p.append(r)


def insert_after(anchor_p, text, template_p):
    newp = copy.deepcopy(template_p._p)
    pPr = newp.find(qn("w:pPr"))
    for child in list(newp):
        if child is not pPr:
            newp.remove(child)
    anchor_p._p.addnext(newp)
    from docx.text.paragraph import Paragraph
    np = Paragraph(newp, anchor_p._p.getparent())
    rebuild(np, text)
    return np


